CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(10) NOT NULL CHECK (role IN ('COACH','ATHLETE'))
);
CREATE TABLE IF NOT EXISTS coaching_relationship (
 coach_id BIGINT NOT NULL REFERENCES app_user(id), athlete_id BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(coach_id, athlete_id), CHECK(coach_id <> athlete_id)
);
CREATE TABLE IF NOT EXISTS planned_session (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, coach_id BIGINT NOT NULL REFERENCES app_user(id),
 athlete_id BIGINT NOT NULL REFERENCES app_user(id), session_date DATE NOT NULL,
 title VARCHAR(120) NOT NULL, type VARCHAR(20) NOT NULL CHECK(type IN ('EASY','FARTLEK','INTERVALS','STRENGTH','REST')),
 notes VARCHAR(2000), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(coach_id, athlete_id) REFERENCES coaching_relationship(coach_id, athlete_id)
);
CREATE INDEX IF NOT EXISTS idx_session_athlete_date ON planned_session(athlete_id,session_date);
CREATE TABLE IF NOT EXISTS session_step (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id BIGINT NOT NULL REFERENCES planned_session(id) ON DELETE CASCADE,
 parent_id BIGINT REFERENCES session_step(id) ON DELETE CASCADE, position INTEGER NOT NULL CHECK(position >= 0),
 kind VARCHAR(10) NOT NULL CHECK(kind IN ('GROUP','RUN','REST')), label VARCHAR(120) NOT NULL,
 repeat_count INTEGER NOT NULL CHECK(repeat_count BETWEEN 1 AND 50), distance_m NUMERIC(10,2),
 target_duration_s NUMERIC(10,2), pace_min_s_per_km NUMERIC(10,2), pace_max_s_per_km NUMERIC(10,2),
 CHECK(distance_m IS NULL OR distance_m > 0), CHECK(target_duration_s IS NULL OR target_duration_s > 0),
 CHECK(pace_min_s_per_km IS NULL OR pace_min_s_per_km > 0), CHECK(pace_max_s_per_km IS NULL OR pace_max_s_per_km > 0),
 CHECK(pace_min_s_per_km IS NULL OR pace_max_s_per_km IS NULL OR pace_min_s_per_km <= pace_max_s_per_km)
);
CREATE TABLE IF NOT EXISTS step_occurrence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id BIGINT NOT NULL REFERENCES planned_session(id) ON DELETE CASCADE,
 step_id BIGINT NOT NULL REFERENCES session_step(id) ON DELETE CASCADE, sequence_no INTEGER NOT NULL,
 occurrence_path VARCHAR(100) NOT NULL, UNIQUE(session_id, sequence_no)
);
CREATE TABLE IF NOT EXISTS session_execution (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id BIGINT NOT NULL UNIQUE REFERENCES planned_session(id),
 athlete_id BIGINT NOT NULL REFERENCES app_user(id), duration_s INTEGER, distance_m NUMERIC(10,2),
 avg_hr INTEGER, max_hr INTEGER, rpe INTEGER, notes VARCHAR(2000), source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(duration_s IS NULL OR duration_s > 0), CHECK(distance_m IS NULL OR distance_m > 0),
 CHECK(avg_hr IS NULL OR avg_hr BETWEEN 30 AND 240), CHECK(max_hr IS NULL OR max_hr BETWEEN 30 AND 240),
 CHECK(rpe IS NULL OR rpe BETWEEN 1 AND 10), CHECK(avg_hr IS NULL OR max_hr IS NULL OR avg_hr <= max_hr)
);
CREATE TABLE IF NOT EXISTS occurrence_result (
 execution_id BIGINT NOT NULL REFERENCES session_execution(id) ON DELETE CASCADE,
 occurrence_id BIGINT NOT NULL REFERENCES step_occurrence(id), duration_s NUMERIC(10,2), distance_m NUMERIC(10,2),
 PRIMARY KEY(execution_id,occurrence_id), CHECK(duration_s IS NULL OR duration_s > 0), CHECK(distance_m IS NULL OR distance_m > 0)
);
